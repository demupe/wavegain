"""Generate checked-in CLI help and manuals from doc/help.json."""
import argparse
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    data = json.loads((ROOT / "doc/help.json").read_text())
    blocks = data["blocks"]
    option_names = re.findall(r'\{"([a-z_-]+)"\s*,', (ROOT / "main.c").read_text())
    all_text = "".join(block["text"] for block in blocks)
    for name in option_names:
        if "--" + name not in all_text:
            raise SystemExit("Missing help for --" + name)
    version = re.search(r'#define WAVEGAIN_VERSION "([^"]+)"', (ROOT / "main.h").read_text()).group(1)
    c = "/* Generated by tools/generate_help.py; edit doc/help.json. */\n"
    text = ""
    for block in blocks:
        condition = block["condition"]
        if condition:
            c += f"#ifdef {condition}\n"
            text += "[Windows builds only]\n" if condition == "_WIN32" else "[Builds with recursive/pattern support]\n"
        c += "    fputs(" + json.dumps(block["text"], ensure_ascii=True) + ", stdout);\n"
        if condition:
            c += "#endif\n"
        text += block["text"]
    text = f"WaveGain v{version}\n" + text
    readme = (ROOT / "README").read_text().split("Documentation (from wavegain --help)")[0]
    readme += "Documentation (from wavegain --help)\n" + "-" * 79 + "\n"
    readme += "Generated from doc/help.json; run make docs after editing.\n\n" + text
    roff_text = text.replace("\\", "\\e").replace("-", "\\-")
    roff_text = "\n".join("\\&" + line if line.startswith((".", "'")) else line for line in roff_text.splitlines())
    man = ('.\\" Generated from doc/help.json; do not edit.\n'
           '.TH WAVEGAIN 1 "' + data['manual_date'] + '" "WaveGain ' + version + '"\n'
           '.SH NAME\nwavegain \\- apply ReplayGain to PCM WAV and Sony Wave64 audio\n'
           '.SH DESCRIPTION\n.nf\n' + roff_text + '\n.fi\n')
    page = ('<!doctype html>\n<html lang="en"><meta charset="utf-8">\n'
            '<title>WaveGain ' + version + '</title>\n'
            '<style>body{max-width:76em;margin:2em auto;padding:0 1em;font:16px system-ui}pre{white-space:pre-wrap}</style>\n'
            '<h1>WaveGain ' + version + '</h1>\n'
            '<p>ReplayGain adjusts the audio samples. Applying gain and undoing it are lossy.</p>\n'
            '<p>Generated from doc/help.json. <a href="legacy-notes.txt">Historical manual notes</a>.</p>\n<pre>' + html.escape(text) + '</pre>\n</html>\n')
    return {"help_generated.h": c, "README": readme, "debian/wavegain.1": man, "doc/manual/index.html": page}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, text in generated_files().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        raise SystemExit("Outdated help/manuals: " + ", ".join(stale) + "; run make docs")


if __name__ == "__main__":
    main()
